    fun translate(language: String?, text: String): String {
        if (language != "fa" || text.isEmpty()) return text
        fa[text]?.let { return it }
        for ((regex, format) in patterns) {
            val match = regex.matchEntire(text) ?: continue
            return format(match)
        }
        return text
    }
}

@Composable
fun tr(text: String): String {
    val locales = LocalConfiguration.current.locales
    val language = if (locales.size() > 0) locales.get(0)?.language else null
    return UiText.translate(language, text)
}

